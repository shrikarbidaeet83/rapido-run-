// Builds the static front end (for Vercel or any static host) into ./dist:
//   public/*  -> dist/*
//   shared/*  -> dist/shared/*
//   dist/config.js points at the game server from GAME_SERVER_URL.
// Usage: GAME_SERVER_URL=https://my-server.onrender.com node scripts/build-static.js [outDir]
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

export function buildStatic(outDir = path.join(ROOT, 'dist'), serverUrl = process.env.GAME_SERVER_URL || '') {
  serverUrl = serverUrl.trim().replace(/\/+$/, '');
  if (serverUrl && !/^https?:\/\/[^\s'"\\]+$/.test(serverUrl)) {
    throw new Error(`GAME_SERVER_URL must look like https://host[:port], got "${serverUrl}"`);
  }
  fs.rmSync(outDir, { recursive: true, force: true });
  fs.cpSync(path.join(ROOT, 'public'), outDir, { recursive: true });
  fs.cpSync(path.join(ROOT, 'shared'), path.join(outDir, 'shared'), { recursive: true });
  fs.writeFileSync(path.join(outDir, 'config.js'),
    `// generated by scripts/build-static.js\nwindow.TINY_RACERS_SERVER = ${JSON.stringify(serverUrl)};\n`);
  return { outDir, serverUrl };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const { outDir, serverUrl } = buildStatic(process.argv[2] ? path.resolve(process.argv[2]) : undefined);
  if (!serverUrl) console.warn('warning: GAME_SERVER_URL is not set; the page will look for the game server on its own origin');
  console.log(`static front end written to ${outDir} (game server: ${serverUrl || 'same origin'})`);
}
